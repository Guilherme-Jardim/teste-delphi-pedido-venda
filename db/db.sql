SET SQL DIALECT 3;

/* ------------------------------------------------------------------ */
/* Tabelas                                                             */
/* ------------------------------------------------------------------ */

CREATE TABLE CLIENTE (
    CODIGO  INTEGER      NOT NULL,
    NOME    VARCHAR(100) NOT NULL,
    CIDADE  VARCHAR(60)  NOT NULL,
    UF      CHAR(2)      NOT NULL,
    CONSTRAINT PK_CLIENTE PRIMARY KEY (CODIGO)
);

CREATE TABLE PRODUTO (
    CODIGO       INTEGER       NOT NULL,
    DESCRICAO    VARCHAR(100)  NOT NULL,
    PRECO_VENDA  NUMERIC(15,2) NOT NULL,
    CONSTRAINT PK_PRODUTO PRIMARY KEY (CODIGO),
    CONSTRAINT CK_PRODUTO_PRECO CHECK (PRECO_VENDA >= 0)
);

CREATE SEQUENCE GEN_PEDIDO_NUMERO;

CREATE TABLE PEDIDO (
    NUMERO_PEDIDO   INTEGER       NOT NULL,
    DATA_EMISSAO    DATE          DEFAULT CURRENT_DATE NOT NULL,
    CODIGO_CLIENTE  INTEGER       NOT NULL,
    VALOR_TOTAL     NUMERIC(15,2) DEFAULT 0 NOT NULL,
    OBSERVACAO      VARCHAR(200),
    CONSTRAINT PK_PEDIDO PRIMARY KEY (NUMERO_PEDIDO),
    CONSTRAINT FK_PEDIDO_CLIENTE FOREIGN KEY (CODIGO_CLIENTE)
        REFERENCES CLIENTE (CODIGO)
        USING INDEX IDX_PEDIDO_CLIENTE
);

CREATE TABLE PEDIDO_ITEM (
    ID              INTEGER GENERATED BY DEFAULT AS IDENTITY,
    NUMERO_PEDIDO   INTEGER       NOT NULL,
    CODIGO_PRODUTO  INTEGER       NOT NULL,
    QUANTIDADE      NUMERIC(15,3) NOT NULL,
    VLR_UNITARIO    NUMERIC(15,2) NOT NULL,
    VLR_TOTAL       NUMERIC(15,2) NOT NULL,
    CONSTRAINT PK_PEDIDO_ITEM PRIMARY KEY (ID),
    CONSTRAINT FK_ITEM_PEDIDO FOREIGN KEY (NUMERO_PEDIDO)
        REFERENCES PEDIDO (NUMERO_PEDIDO) ON DELETE CASCADE
        USING INDEX IDX_PEDIDO_ITEM_PEDIDO,
    CONSTRAINT FK_ITEM_PRODUTO FOREIGN KEY (CODIGO_PRODUTO)
        REFERENCES PRODUTO (CODIGO)
        USING INDEX IDX_PEDIDO_ITEM_PRODUTO,
    CONSTRAINT CK_ITEM_QUANTIDADE CHECK (QUANTIDADE > 0),
    CONSTRAINT CK_ITEM_VLR_UNITARIO CHECK (VLR_UNITARIO >= 0)
);

/*
  Indices: PEDIDO(CODIGO_CLIENTE), PEDIDO_ITEM(NUMERO_PEDIDO) e
  PEDIDO_ITEM(CODIGO_PRODUTO) sao criados junto com as respectivas FKs
  (clausula USING INDEX), para o Firebird nao duplicar o indice.
*/

